# Pograma para ler um número qualquer e mostrar seu dobro, tripo e raiz quadrada

numeroInteiro = int(input('Insira um número: '))
dobro = numeroInteiro * 2
triplo = numeroInteiro * 3
raizq = numeroInteiro ** (1/2)
print(f'O resultado do dobro, triplo e raiz quadrado de {numeroInteiro} é {dobro}, {triplo} e {raizq}')
